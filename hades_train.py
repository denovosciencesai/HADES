# Trainer                                                                      #
# --------------------------------------------------------------------------- #
class HADESTrainer:
    def __init__(
        self,
        output_dir: Optional[str] = None,
        smiles_col: str = "SMILES",
        label_col: str = "phase",
        positive_label: Union[str, int] = 4,
        negative_label: Optional[Union[str, int]] = 0,
        n_per_class: Optional[int] = None,
        test_size: float = 0.2,
        random_state: int = 42,
        use_gpu: bool = False,
        param_spaces: Optional[dict] = None,
        overwrite: bool = False,
    ):
        self.output_dir = output_dir or "hades_run_" + _dt.datetime.now().strftime("%Y%m%d_%H%M%S")
        self.smiles_col = smiles_col
        self.label_col = label_col
        self.positive_label = positive_label
        self.negative_label = negative_label
        self.n_per_class = n_per_class
        self.test_size = test_size
        self.random_state = random_state
        self.use_gpu = use_gpu
        self.overwrite = overwrite
        self.param_spaces = param_spaces or default_param_spaces(use_gpu)
        self.featurizer = Featurizer()

    def _prepare_output_dir(self) -> str:
        if os.path.exists(self.output_dir) and not self.overwrite:
            raise FileExistsError(
                f"Output folder already exists: {self.output_dir}\n"
                "Choose a different -o/--output-dir, or pass --overwrite."
            )
        os.makedirs(os.path.join(self.output_dir, "data"), exist_ok=True)
        os.makedirs(os.path.join(self.output_dir, "models"), exist_ok=True)
        return self.output_dir

    def load_dataset(self, csv_path: str) -> pd.DataFrame:
        if not os.path.exists(csv_path):
            raise FileNotFoundError(f"Input CSV not found: {csv_path}")
        df = pd.read_csv(csv_path)
        for col in (self.smiles_col, self.label_col):
            if col not in df.columns:
                raise KeyError(f"Column '{col}' not in CSV. Available: {list(df.columns)}")
        if self.negative_label is not None:
            df = df[df[self.label_col].isin([self.positive_label, self.negative_label])].copy()
        df["_target"] = (df[self.label_col] == self.positive_label).astype(int)
        counts = Counter(df["_target"])
        if counts.get(1, 0) == 0 or counts.get(0, 0) == 0:
            raise ValueError(
                f"Need both classes. Found {counts.get(1, 0)} positive / "
                f"{counts.get(0, 0)} negative. Check label settings."
            )
        if self.n_per_class is not None:
            df = (df.groupby("_target", group_keys=False)
                    .apply(lambda g: g.sample(n=min(self.n_per_class, len(g)),
                                              random_state=self.random_state))
                    .reset_index(drop=True))
        logger.info("Loaded %d molecules (%d positive / %d negative).",
                    len(df), int(df["_target"].sum()), int((1 - df["_target"]).sum()))
        return df

    def featurize(self, df: pd.DataFrame) -> pd.DataFrame:
        feats = self.featurizer.featurize_many_smiles(df[self.smiles_col])
        logger.info("All-features shape: %s", feats.shape)
        feats = self.featurizer.drop_na_cols(feats)
        feats = self.featurizer.drop_same_val_cols(feats)
        feats.columns = feats.columns.astype(str)
        logger.info("After dropping invalid features: %s", feats.shape)
        return feats

    def select_features(self, X_train, y_train):
        selector = RandomForestClassifier(n_estimators=1000, n_jobs=-1,
                                          random_state=self.random_state)
        corrdrop = CorrDrop(selector)
        thresh, thresh_std = corrdrop.get_corr_threshold(X_train, y_train)
        keep_cols, opt_threshold = corrdrop.get_cols_to_keep(X_train, thresh, thresh_std)
        logger.info("Selected %d features at correlation threshold %.3f.",
                    len(keep_cols), opt_threshold)
        return list(keep_cols), float(opt_threshold)

    def run_hpo(self, out_dir, X, y, reuse: bool) -> dict:
        hpo_path = os.path.join(out_dir, "hyperparameters.json")
        if reuse and os.path.exists(hpo_path):
            logger.info("Reusing hyper-parameters from %s", hpo_path)
            with open(hpo_path) as f:
                return json.load(f)
        logger.info("Running hyper-parameter optimisation ...")
        results = HPOptimizer(self.param_spaces, X, y).param_search()
        with open(hpo_path, "w") as f:
            json.dump(results, f, indent=4)
        logger.info("Saved hyper-parameters to %s", hpo_path)
        return results

    def train_ensemble(self, X_train, y_train, results) -> dict:
        y = list(map(int, y_train))
        sample_weights = compute_sample_weight(class_weight="balanced", y=y)
        counts = Counter(y)
        total = sum(counts.values())
        catboost_weights = [total / counts[c] for c in sorted(counts)]
        trained = {}
        for name, ctor in tqdm(MODEL_REGISTRY.items(), desc="Training models"):
            best = dict(results[name]["best_params"])
            if name == "CatBoostClassifier":
                best.setdefault("random_seed", self.random_state)
                model = ctor(class_weights=catboost_weights, verbose=0, **best)
                trained[name] = model.fit(X_train, y)
            else:
                best.setdefault("random_state", self.random_state)
                model = ctor(eval_metric="logloss", **best) if name == "XGBClassifier" else ctor(**best)
                trained[name] = model.fit(X_train, y, sample_weight=sample_weights)
        return trained

    def run(self, csv_path: str, reuse_hpo: bool = False) -> str:
        out_dir = self._prepare_output_dir()
        logger.info("Output folder: %s", out_dir)

        df = self.load_dataset(csv_path)
        feats = self.featurize(df)
        target = df["_target"].loc[feats.index]
        smiles = df[self.smiles_col].loc[feats.index]

        X_train, X_test, y_train, y_test, smi_train, smi_test = train_test_split(
            feats, target, smiles, test_size=self.test_size,
            random_state=self.random_state, stratify=target)

        keep_cols, opt_threshold = self.select_features(X_train, y_train)
        X_train, X_test = X_train[keep_cols], X_test[keep_cols]
        X_train.columns = X_train.columns.astype(str)
        X_test.columns = X_test.columns.astype(str)

        data_dir = os.path.join(out_dir, "data")
        xtr = X_train.copy(); xtr["SMILES"] = smi_train.values
        xte = X_test.copy();  xte["SMILES"] = smi_test.values
        xtr.to_parquet(os.path.join(data_dir, "X_train.parquet"))
        xte.to_parquet(os.path.join(data_dir, "X_test.parquet"))
        y_train.to_csv(os.path.join(data_dir, "y_train.csv"))
        y_test.to_csv(os.path.join(data_dir, "y_test.csv"))

        with open(os.path.join(out_dir, "param_spaces.json"), "w") as f:
            json.dump(param_spaces_to_json(self.param_spaces), f, indent=4)

        results = self.run_hpo(out_dir, X_train, np.asarray(y_train), reuse=reuse_hpo)
        models = self.train_ensemble(X_train, y_train, results)
        for name, model in models.items():
            joblib.dump(model, os.path.join(out_dir, "models", f"{name}.pkl"))

        config = {
            "created": _dt.datetime.now().isoformat(timespec="seconds"),
            "output_dir": out_dir,
            "smiles_col": self.smiles_col,
            "label_col": self.label_col,
            "positive_label": self.positive_label,
            "negative_label": self.negative_label,
            "test_size": self.test_size,
            "random_state": self.random_state,
            "use_gpu": self.use_gpu,
            "n_train": int(len(X_train)),
            "n_test": int(len(X_test)),
            "opt_threshold": opt_threshold,
            "descriptor_cols": keep_cols,
            "model_names": list(models.keys()),
        }
        with open(os.path.join(out_dir, "config.json"), "w") as f:
            json.dump(config, f, indent=4)

        # Drop the ready-to-run scorer into the folder (HADES path baked in).
        score_path = write_scorer(out_dir)
        logger.info("Wrote scorer: %s", score_path)

        logger.info("Training complete. To score new molecules:")
        logger.info("    python %s INPUT.csv OUTPUT.csv --smiles-col SMILES", score_path)
        return out_dir


