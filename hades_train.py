def _parse_label(value: str) -> Union[str, int]:
    try:
        return int(value)
    except (TypeError, ValueError):
        return value


def _cmd_train(args) -> None:
    param_spaces = None
    if args.param_config:
        with open(args.param_config) as f:
            param_spaces = param_spaces_from_json(json.load(f))
        logger.info("Loaded custom search space from %s", args.param_config)
    negative = None if str(args.negative_label).lower() == "none" \
        else _parse_label(args.negative_label)

    # Let the user name the folder interactively if they didn't pass -o.
    output_dir = args.output_dir
    if not output_dir:
        try:
            entered = input(
                "Name the output folder for this run "
                "(leave blank for an automatic name): "
            ).strip()
        except EOFError:
            entered = ""
        output_dir = entered or None

    HADESTrainer(
        output_dir=output_dir,
        smiles_col=args.smiles_col,
        label_col=args.label_col,
        positive_label=_parse_label(args.positive_label),
        negative_label=negative,
        n_per_class=args.n_per_class,
        test_size=args.test_size,
        random_state=args.random_state,
        use_gpu=args.use_gpu,
        param_spaces=param_spaces,
        overwrite=args.overwrite,
    ).run(args.input_csv, reuse_hpo=args.reuse_hpo)


def _cmd_dump_config(args) -> None:
    with open(args.output_json, "w") as f:
        json.dump(param_spaces_to_json(default_param_spaces()), f, indent=4)
    logger.info("Wrote default search space to %s. Edit it, then pass it to "
                "`train --param-config`.", args.output_json)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="HADES training pipeline (named output folders + auto scorer).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    t = sub.add_parser("train", help="Train into a named output folder.")
    t.add_argument("input_csv", help="CSV with SMILES and a label column.")
    t.add_argument("-o", "--output-dir", default=None,
                   help="Folder to create for this run (default: timestamped name).")
    t.add_argument("--smiles-col", default="SMILES")
    t.add_argument("--label-col", default="phase")
    t.add_argument("--positive-label", default="4")
    t.add_argument("--negative-label", default="0",
                   help="Use 'none' to treat everything not positive as negative.")
    t.add_argument("--n-per-class", type=int, default=None)
    t.add_argument("--test-size", type=float, default=0.2)
    t.add_argument("--random-state", type=int, default=42)
    t.add_argument("--param-config", default=None,
                   help="JSON search space from `dump-config`.")
    t.add_argument("--use-gpu", action="store_true")
    t.add_argument("--reuse-hpo", action="store_true")
    t.add_argument("--overwrite", action="store_true")
    t.set_defaults(func=_cmd_train)

    d = sub.add_parser("dump-config", help="Write the default search space to JSON.")
    d.add_argument("output_json")
    d.set_defaults(func=_cmd_dump_config)
    return p


def main() -> None:
    args = build_parser().parse_args()
    args.func(args)


if __name__ == "__main__":
    main()