def _hades_parent_dir() -> Optional[str]:
    """Absolute path to the folder that contains the importable HADES package."""
    try:
        import HADES as _h
        f = getattr(_h, "__file__", None)
        if f:
            return os.path.dirname(os.path.dirname(os.path.abspath(f)))
    except Exception:
        pass
    return None


def write_scorer(output_dir: str) -> str:
    """(Re)write score.py into `output_dir` with the HADES path baked in.

    Can be called on an EXISTING run folder without retraining, e.g.:
        from hades_pipeline import write_scorer
        write_scorer("my_experiment")
    """
    script = SCORE_SCRIPT.replace("__HADES_PARENT__", repr(_hades_parent_dir()))
    path = os.path.join(output_dir, "score.py")
    with open(path, "w") as f:
        f.write(script)
    return path


