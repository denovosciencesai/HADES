"""
hades_pipeline.py
=================
Train a HADES ensemble into a NAMED, self-contained output folder, and have a
ready-to-run `score.py` dropped into that folder automatically.

You choose the folder name; everything for that run goes inside it:

    <your-folder>/
        config.json            <- settings + the exact feature columns
        param_spaces.json       <- the hyper-parameter search space used
        hyperparameters.json    <- best params found
        data/                   <- train/test splits
        models/                 <- one .pkl per ensemble member
        score.py                <- AUTO-GENERATED; scores new molecules

Because each run has its own folder, runs never overwrite each other.

Command-line usage
------------------
Train into a folder you name:

    python hades_pipeline.py train my_data.csv -o experiment_A \
        --label-col activity --positive-label active --negative-label inactive

Score new molecules using the auto-generated script in that folder:

    python experiment_A/score.py new_molecules.csv scored.csv --smiles-col SMILES

Customise the search space:

    python hades_pipeline.py dump-config my_space.json   # writes the default
    # edit ranges in my_space.json ...
    python hades_pipeline.py train my_data.csv -o experiment_B --param-config my_space.json

Requires the local `HADES` package (Featurizer, CorrDrop, HPOptimizer).
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import logging
import os
from collections import Counter
from typing import Optional, Union

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import (
    HistGradientBoostingClassifier,
    RandomForestClassifier,
)
from sklearn.model_selection import train_test_split
from sklearn.utils import compute_sample_weight
from tqdm import tqdm

from catboost import CatBoostClassifier
from lightgbm import LGBMClassifier
from xgboost import XGBClassifier

from HADES.featurize import Featurizer
from HADES.correlation_drop import CorrDrop
from HADES.ml_modeling import HPOptimizer
from HADES.param_spaces import default_param_spaces
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("hades")

MODEL_REGISTRY = {
    "XGBClassifier": XGBClassifier,
    "CatBoostClassifier": CatBoostClassifier,
    "LGBMClassifier": LGBMClassifier,
    "RandomForestClassifier": RandomForestClassifier,
    "HistGradientBoostingClassifier": HistGradientBoostingClassifier,
}


# --------------------------------------------------------------------------- #
# The scoring script that gets written into every run folder.                 #
# It reads config.json + models/ located next to itself, so it is portable.   #
# --------------------------------------------------------------------------- #
SCORE_SCRIPT = r'''# Auto-generated by hades_pipeline.py -- do not edit by hand.
# Scores new molecules using the models saved in THIS folder.
#
# Usage:
#     python score.py input.csv output.csv --smiles-col SMILES
#
# Finding the HADES package (you do NOT need to copy HADES into this folder):
#   1. The absolute path to HADES, baked in when this run was trained, is tried
#      first (see _HADES_PARENT below).
#   2. If that path no longer exists (e.g. you moved the repo), the script walks
#      upward from its own location looking for a HADES/ folder.
import argparse
import json
import os
import sys

import joblib
import numpy as np
import pandas as pd

RUN_DIR = os.path.dirname(os.path.abspath(__file__))

# Absolute path to the folder that CONTAINS the HADES package, captured at
# training time. Replaced automatically when this file is generated.
_HADES_PARENT = __HADES_PARENT__


def _ensure_hades_importable(start_dir, baked):
    # 1) Prefer the baked-in absolute path if it still holds a HADES/ folder.
    if baked and os.path.isdir(os.path.join(baked, "HADES")):
        if baked not in sys.path:
            sys.path.insert(0, baked)
        return baked
    # 2) Otherwise walk upward looking for a folder that contains HADES/.
    d = start_dir
    for _ in range(6):
        if os.path.isdir(os.path.join(d, "HADES")):
            if d not in sys.path:
                sys.path.insert(0, d)
            return d
        parent = os.path.dirname(d)
        if parent == d:
            break
        d = parent
    # 3) Last resort: the folder one level above this script.
    parent = os.path.dirname(start_dir)
    if parent and parent not in sys.path:
        sys.path.insert(0, parent)
    return parent


_ensure_hades_importable(RUN_DIR, _HADES_PARENT)

from HADES.featurize import Featurizer


def load_run():
    with open(os.path.join(RUN_DIR, "config.json")) as f:
        config = json.load(f)
    models = {}
    for name in config["model_names"]:
        models[name] = joblib.load(os.path.join(RUN_DIR, "models", name + ".pkl"))
    return config, models


def featurize(smiles_list, descriptor_cols):
    featurizer = Featurizer()
    feats = featurizer.featurize_many_smiles(smiles_list)
    feats.columns = feats.columns.astype(str)
    missing = [c for c in descriptor_cols if c not in feats.columns]
    if missing:
        print("WARNING:", len(missing), "expected features missing; filled with NaN.")
    X = feats.reindex(columns=descriptor_cols)
    return X.apply(pd.to_numeric, errors="coerce")


def score(smiles_list, config, models):
    X = featurize(smiles_list, config["descriptor_cols"])
    probs = [m.predict_proba(X)[:, 1] for m in models.values()]
    return np.mean(probs, axis=0)


def main():
    p = argparse.ArgumentParser(description="Score molecules with this HADES run.")
    p.add_argument("input_csv", help="CSV of molecules to score.")
    p.add_argument("output_csv", help="Where to write the scored CSV.")
    p.add_argument("--smiles-col", default="SMILES")
    args = p.parse_args()

    config, models = load_run()
    print("Loaded", len(models), "models trained on", config["created"])

    df = pd.read_csv(args.input_csv)
    if args.smiles_col not in df.columns:
        raise KeyError("Column '" + args.smiles_col + "' not in " + args.input_csv +
                       ". Available: " + str(list(df.columns)))

    df["HADES_Score"] = score(df[args.smiles_col].tolist(), config, models)
    df.to_csv(args.output_csv, index=False)
    print("Wrote", len(df), "scored rows to", args.output_csv)


if __name__ == "__main__":
    main()
'''


