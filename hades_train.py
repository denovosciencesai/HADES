def param_spaces_to_json(spaces: dict) -> dict:
    out = {}
    for cls, spec in spaces.items():
        name = cls.__name__ if isinstance(cls, type) else str(cls)
        out[name] = {
            "params": {k: list(v) for k, v in spec["params"].items()},
            "extra_args": spec.get("extra_args", {}),
        }
    return out


def param_spaces_from_json(data: dict) -> dict:
    out = {}
    for name, spec in data.items():
        if name not in MODEL_REGISTRY:
            raise KeyError(
                f"Unknown model '{name}' in param config. Valid: {list(MODEL_REGISTRY)}"
            )
        out[MODEL_REGISTRY[name]] = {
            "params": {k: tuple(v) for k, v in spec["params"].items()},
            "extra_args": spec.get("extra_args", {}),
        }
    return out


